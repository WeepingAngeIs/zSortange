"""Test-only process cuts in two brand-new isolated worlds, using the packaged JAR.
This samples explicit boundaries, not arbitrary power-loss atomicity between region/player saves.
"""
from pathlib import Path
import json,os,shutil,subprocess
root=Path.cwd().resolve();base=root/'build/acceptance';source=base/'server';evidence=base/'evidence'
assert os.environ.get('GITHUB_ACTIONS')=='true','Requires a disposable GitHub runner'
assert (source/'libraries/net/neoforged/neoforge/21.1.249/unix_args.txt').is_file(),'No isolated installed runtime to reuse'
jar=next(p for p in (root/'build/libs').glob('anya-storage-plus-*.jar') if not p.name.endswith('-sources.jar'))

def create(name):
    d=base/name;assert not d.exists(),'Refusing to reuse fault test directory';d.mkdir()
    shutil.copytree(source/'libraries',d/'libraries',copy_function=os.link)
    shutil.copytree(source/'mods',d/'mods')
    (d/'.anya-disposable-fixture').write_text('Generated by fault_acceptance.py on an ephemeral CI runner\n')
    (d/'eula.txt').write_text('eula=true\n')
    (d/'server.properties').write_text('level-name=world\nlevel-type=minecraft:flat\ngenerate-structures=false\nonline-mode=false\nview-distance=2\nsimulation-distance=2\nspawn-protection=0\nserver-ip=127.0.0.1\nserver-port=25576\nallow-flight=true\nmax-tick-time=120000\n')
    return d

def run(d,mode,code,marker):
    ctrl=d/'control';ctrl.mkdir(exist_ok=True)
    cmd=['java','-Xmx1200m','-Xms256m','-Danya.acceptance=true','-Danyastorage.pocketPrototype=true',f'-Danya.fault={mode}',f'-Danya.control={ctrl}',f'-Danya.expectedJar={jar}','@libraries/net/neoforged/neoforge/21.1.249/unix_args.txt','nogui']
    with (evidence/f'fault-{mode}.log').open('w') as log:result=subprocess.run(cmd,cwd=d,stdout=log,stderr=subprocess.STDOUT,timeout=150)
    shutil.copytree(ctrl,evidence/d.name,dirs_exist_ok=True)
    assert result.returncode==code, f'{mode}: exit {result.returncode}, expected {code}'
    failed=list(ctrl.glob('FAILED*'));assert not failed,'\n'.join(p.read_text() for p in failed)
    assert (ctrl/marker).is_file(),f'{mode}: no expected marker {marker}'
    print(f'ANYA_PROCESS_CUT_VERIFIED {mode}: exit={result.returncode} marker={marker}',flush=True)

p=create('fault-preparation')
run(p,'prepare-seed',77,'CUT_PREPARATION')
run(p,'prepare-verify',0,'ANYA_INTERRUPTED_PREPARATION_OK')
t=create('fault-transfer')
run(t,'transfer-seed',77,'CUT_BEFORE_TRANSFER_COMMIT')
run(t,'transfer-commit',77,'CUT_AFTER_TRANSFER_SAVE')
run(t,'transfer-verify',0,'ANYA_SAVED_TRANSFER_RESTART_OK')
print('ANYA_PROCESS_INTERRUPTION_ACCEPTANCE_OK: partial BUILDING fails closed; uncommitted plan disappears; fully saved transfer remains conserved; no arbitrary crash-atomicity claim')
